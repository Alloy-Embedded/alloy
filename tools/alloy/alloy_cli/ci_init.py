"""Write a CI workflow for a project that uses alloy.

The framework's own CI is what keeps every board building; a project built ON
alloy gets nothing by default. This generates the equivalent: validate the
boards it defines, then build its sources for every board it targets.

The workflow is written for the boards the project ACTUALLY has, and installs
only the toolchains those boards need. Emitting an Xtensa download for a project
that only targets STM32 would be four minutes of CI wasted on every push.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .emit.common import EmitError

# Pinned exactly as the framework's own CI pins them: a workflow that drifts
# from the versions alloy is tested against is a workflow that fails for reasons
# the user did not cause.
ARM_RELEASE = "14.2.Rel1"
XTENSA_TAG = "esp-16.1.0_20260609"
XTENSA_ARCHIVE = "xtensa-esp-elf-16.1.0_20260609-x86_64-linux-gnu.tar.xz"

WORKFLOW_PATH = Path(".github/workflows/alloy.yml")


def _xtensa_steps() -> str:
    return f"""
      - name: cache xtensa toolchain
        id: xtensa-cache
        uses: actions/cache@v4
        with:
          path: ~/.alloy/tools/xtensa-esp-elf
          key: {XTENSA_ARCHIVE}
      - name: install xtensa toolchain
        if: steps.xtensa-cache.outputs.cache-hit != 'true'
        run: |
          mkdir -p ~/.alloy/tools && cd ~/.alloy/tools
          curl -sL -o x.tar.xz \\
            "https://github.com/espressif/crosstool-NG/releases/download/{XTENSA_TAG}/{XTENSA_ARCHIVE}"
          tar xf x.tar.xz && rm x.tar.xz
"""


def workflow_yaml(project_name: str, board_ids: list[str],
                  local_boards: list[str], needs_xtensa: bool) -> str:
    """The workflow text. Pure, so a test can read it without touching disk."""
    validate = "".join(
        f"      - name: validate boards/{b}\n"
        f"        run: alloy board-validate {b}\n"
        for b in local_boards)
    board_list = ",".join(board_ids)

    return f"""# GENERATED by `alloy ci-init`. Edit freely — it is yours now.
#
# What this checks, and why:
#   board-validate  a board can name a pin that has no route to its peripheral.
#                   That compiles until something opens the bus, then fails
#                   inside a template. This catches it on every push instead.
#   matrix          builds {project_name}'s sources for every board listed
#                   below. The point of alloy is that one source tree does
#                   that; this is what keeps it true as the code grows. Add
#                   boards to the list to widen the claim.
name: alloy

on:
  push:
  pull_request:

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: astral-sh/setup-uv@v5
      - name: install the alloy CLI
        run: uv tool install alloy-embedded
      - uses: carlosperate/arm-none-eabi-gcc-action@v1
        with:
          release: "{ARM_RELEASE}"{_xtensa_steps() if needs_xtensa else ""}
      - name: install ninja
        run: sudo apt-get update && sudo apt-get install -y ninja-build
{validate}      - name: build for every target board
        run: alloy matrix --boards {board_list}
"""


def plan(project: Any, alloy_root: Path, boards: list[str] | None = None,
         every_board: bool = False) -> dict[str, Any]:
    """What the workflow should contain for this project.

    Defaults to what the project actually targets — its declared board plus any
    it defines locally. Widening that to every supported board is a real option
    (`--all`) but a poor default: it would make a single-board project download
    an Xtensa toolchain on every push to prove a portability it never claimed.
    """
    from .matrix import known_boards  # noqa: PLC0415

    local_dir = project.root / "boards"
    local = sorted(b.name for b in local_dir.iterdir()
                   if (b / "board.json").exists()) if local_dir.is_dir() else []

    if boards:
        chosen = sorted(set(boards))
    elif every_board:
        chosen = known_boards(alloy_root, project.root)
    else:
        chosen = sorted({project.board_id, *local})

    return {
        "boards": chosen, "local_boards": local,
        "needs_xtensa": any(b.startswith("esp") for b in chosen),
    }


def write_workflow(project: Any, alloy_root: Path, force: bool = False,
                   boards: list[str] | None = None,
                   every_board: bool = False) -> tuple[Path, dict]:
    details = plan(project, alloy_root, boards, every_board)
    path = project.root / WORKFLOW_PATH
    if path.exists() and not force:
        raise EmitError(f"{WORKFLOW_PATH} already exists — pass --force to replace it")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(workflow_yaml(
        project.name, details["boards"], details["local_boards"], details["needs_xtensa"]))
    return path, details
