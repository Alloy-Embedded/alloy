"""Emit alloy/ota_key.hpp — the update root of trust as generated data.

The trusted key(s) are a PROJECT fact (alloy.toml `[ota]`), not a board or chip
one: the same board signed by two vendors is two different products. Always
emitted, so `#include <alloy/ota_key.hpp>` compiles everywhere and firmware picks
the path with `if constexpr (alloy::ota_key::configured)` — no preprocessor
conditional in user code (NORTH_STAR guard #3).

Two spellings, and they mean the same thing to the device:

    [ota]
    public_key = "update_key.pub"                    # a ring of one

    [ota]
    public_keys = ["retired", "rotate_key.pub"]      # key_id 0 retired, 1 live

`public_keys` is the KEY ROTATION surface. The list is positional: entry *i* is
the key an image selects with `alloy image --key-id i`. So a key is retired by
replacing its entry with "retired" (or ""), NEVER by deleting it — deleting
entry 0 would silently re-point every image that names key 0 at what used to be
key 1. A retired entry is emitted as 32 zero bytes, which alloy/ota/signed.hpp
refuses before it ever calls Ed25519.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .common import EmitError

_BANNER = "// GENERATED by alloy — DO NOT EDIT (fix alloy.toml [ota] and regenerate)\n"

#: How many keys a ring may hold. Not a technical limit — 32 B of .rodata each —
#: but a ring nobody can enumerate is a ring nobody audits, and `key_id` is a
#: u16 on the wire so the format itself allows far more than anyone should use.
MAX_RING_KEYS = 8

#: Spellings that mark a ring entry as retired rather than naming a key file.
RETIRED = ("", "retired", "revoked")


def load_public_key(value: str, project_root: Path) -> bytes:
    """Accept 64 hex chars inline, or a path (relative to the project) to a
    file holding them — what `alloy keygen` writes as <name>.pub."""
    text = value.strip()
    candidate = project_root / text
    if candidate.exists():
        text = candidate.read_text().strip()
    text = "".join(text.split())
    try:
        key = bytes.fromhex(text)
    except ValueError as exc:
        raise EmitError(f"[ota] public_key: not hex ({exc}) — expected 64 hex "
                        f"chars or a path to an `alloy keygen` .pub file") from exc
    if len(key) != 32:
        raise EmitError(f"[ota] public_key: Ed25519 keys are 32 bytes, got {len(key)}")
    return key


def load_key_ring(ota: dict[str, Any], project_root: Path) -> list[bytes] | None:
    """The trusted key ring in key_id order, or None when the project configures
    no key at all (integrity-only v1 behaviour). A retired entry is 32 zeroes."""
    single = ota.get("public_key")
    ring = ota.get("public_keys")
    if single is not None and ring is not None:
        raise EmitError("[ota]: give either public_key (one key) or public_keys "
                        "(a rotation ring), not both")
    if single is not None:
        return [load_public_key(single, project_root)]
    if ring is None:
        return None
    if not isinstance(ring, list) or not ring:
        raise EmitError("[ota] public_keys: expected a non-empty list of .pub "
                        'paths / 64-hex keys, with "retired" for a retired slot')
    if len(ring) > MAX_RING_KEYS:
        raise EmitError(f"[ota] public_keys: {len(ring)} keys exceeds the "
                        f"{MAX_RING_KEYS}-key ring limit")
    keys: list[bytes] = []
    for i, entry in enumerate(ring):
        if not isinstance(entry, str):
            raise EmitError(f"[ota] public_keys[{i}]: expected a string, got "
                            f"{type(entry).__name__}")
        if entry.strip().lower() in RETIRED:
            keys.append(bytes(32))  # retired: refused on-device before Ed25519
            continue
        keys.append(load_public_key(entry, project_root))
    if all(k == bytes(32) for k in keys):
        raise EmitError("[ota] public_keys: every entry is retired — no image "
                        "could ever be accepted, and the device would be "
                        "un-updatable. Add the replacement key first.")
    seen: dict[bytes, int] = {}
    for i, k in enumerate(keys):
        if k == bytes(32):
            continue
        if k in seen:
            raise EmitError(f"[ota] public_keys: entries {seen[k]} and {i} are "
                            f"the SAME key — retiring one would leave the other "
                            f"accepting the same signatures")
        seen[k] = i
    return keys


def _rows(key: bytes) -> str:
    return ",\n        ".join(
        ", ".join(f"0x{b:02X}" for b in key[i:i + 8]) for i in range(0, 32, 8))


def emit_ota_key_header(keys: list[bytes] | None) -> str:
    if not keys:
        body = """// No [ota] public_key/public_keys in alloy.toml: images are checked for
// INTEGRITY only (CRC), so updates must ride a trusted channel. Add a key to
// require authenticity — see `alloy keygen`.
inline constexpr bool configured = false;
inline constexpr std::uint16_t key_count = 0;
inline constexpr std::uint8_t public_keys[1][32] = {};
inline constexpr const std::uint8_t* public_key = &public_keys[0][0];"""
    else:
        entries = "\n".join(
            f"    {{  // key_id {i}"
            f"{'  — RETIRED (all zero: refused before Ed25519 runs)' if k == bytes(32) else ''}\n"
            f"        {_rows(k)},\n    }},"
            for i, k in enumerate(keys))
        body = f"""// The update root of trust: only images signed by a matching PRIVATE key
// (kept off this machine — see `alloy image --sign`) will boot. The image
// header's key_id (offset 22) selects the ring entry; `alloy image --key-id N`
// sets it, and 0 is what every image written before the field existed carries.
inline constexpr bool configured = true;
inline constexpr std::uint16_t key_count = {len(keys)};
inline constexpr std::uint8_t public_keys[{len(keys)}][32] = {{
{entries}
}};
// The v2 spelling, kept so single-key firmware needs no edit: ring entry 0.
inline constexpr const std::uint8_t* public_key = &public_keys[0][0];"""
    return f"""{_BANNER}#pragma once

#include <cstdint>

namespace alloy::ota_key {{

{body}

}}  // namespace alloy::ota_key
"""
