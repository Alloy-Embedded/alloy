def _resolve(chip: dict[str, Any], board: dict[str, Any]):
    """Shared gate: returns (cpu, uart_name, periph, model, irq_number) or raises
    EmitError if this board/chip is not Renode-emulable."""
    arch = chip["cores"][0]["arch"]
    cpu = RENODE_CPU.get(arch)
    if cpu is None:
        raise EmitError(f"renode: no CPU mapping for arch '{arch}'")

    roles = board.get("roles") or board
    uart_role = roles.get("debug_uart")
    if not uart_role or "peripheral" not in uart_role:
        raise EmitError("renode: board has no debug_uart role to observe")
    name = uart_role["peripheral"]

    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        raise EmitError(f"renode: debug_uart peripheral '{name}' is not curated")
    model = RENODE_UART.get(periph.get("ip"))
    if model is None:
        raise EmitError(f"renode: no UART model for ip '{periph.get('ip')}'")

    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        raise EmitError(f"renode: debug_uart peripheral '{name}' has no mapped IRQ")
    return cpu, name, periph, model, irqn


def _resolve_i2c(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the I2C controller: returns (name, base, model, irq) if
    the board has a curated i2c role whose IP Renode models, else None. Never
    raises — I2C is an ADDITION to the platform, so a board without it just emits
    the CPU/UART platform unchanged."""
    roles = board.get("roles") or board
    role = roles.get("i2c")
    if not role or "peripheral" not in role:
        return None
    name = role["peripheral"]
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    model = RENODE_I2C.get(periph.get("ip"))
    if model is None:
        return None
    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        return None
    return name, int(periph["base"], 16), model, irqn


