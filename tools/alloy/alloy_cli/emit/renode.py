"""Emit a Renode platform (.repl) + run script (.resc) so CI can EXECUTE
firmware, not just compile it.

The platform is data-driven from the SAME chip/board facts the linker and vector
table consume — CPU, memory map and the debug UART's address/IRQ all come from
alloy-devices, so the emulated target cannot drift from the real one and nothing
here is a hand-maintained silicon fact (guard #1: facts are generated).

Renode's SoC coverage is uneven, so RENODE_CPU / RENODE_UART gate emulation to
the families Renode models well (keyed like debug.py's OPENOCD_TARGET — tool
integration, not silicon facts). An unsupported family raises EmitError and is
simply left out of the emulation matrix. Emulation is an ADDITIONAL honesty gate
("does uart_echo actually boot and print its banner?"), never a substitute for
on-silicon validation.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .common import EmitError

_REPL_BANNER = "// GENERATED by alloy — DO NOT EDIT (fix the data or the emitter and regenerate)\n"
_RESC_BANNER = "# GENERATED by alloy — DO NOT EDIT (fix the data or the emitter and regenerate)\n"

# Cortex-M core arch -> Renode cpuType.
RENODE_CPU = {
    "armv6m": "cortex-m0",
    "armv7m": "cortex-m3",
    "armv7em": "cortex-m7",
    "armv8m_base": "cortex-m23",
    "armv8m_main": "cortex-m33",
    # xtensa_lx6 (ESP32) intentionally absent: Renode Xtensa support is out of scope.
}

# Renode UART peripheral model per debug-UART IP version. Only IPs whose register
# layout Renode models compatibly are listed; a board whose debug UART is absent
# here is left out of the emulation matrix rather than emulated incorrectly.
RENODE_UART = {
    "st/usart_v2": "UART.STM32F7_USART",
    "st/usart_v3": "UART.STM32F7_USART",
    "st/usart_v4": "UART.STM32F7_USART",
    "raspberrypi/uart_pl011": "UART.PL011",
    "microchip/usart_v1": "UART.SAM_USART",  # SAME70/SAMV71 USART (Cortex-M7)
}

# The .repl property that feeds a UART model its input clock. Most Renode UART
# models name it `frequency`; SAM_USART's constructor parameter is `clockFrequency`
# and Renode rejects the platform (E25: no suitable constructor) if the name is
# wrong. The VALUE is immaterial to the headless terminal tester — it reads a
# logical byte stream, not a real baud rate — but the NAME must match the model.
_UART_CLOCK_PROP = {
    "UART.SAM_USART": "clockFrequency",
}

# Renode I2C CONTROLLER model per IP version — same idea as RENODE_UART, and the
# same honesty rule: only IPs whose register layout Renode models compatibly are
# listed. This adds the real silicon controller to the emulated platform (a
# faithful, data-driven addition); the DummyI2CSlave a conformance test needs is a
# TEST FIXTURE the Robot attaches at runtime, not something the platform emitter
# bakes in. A board without a curated i2c role, or whose i2c IP is absent here,
# simply gets no I2C block — the rest of the platform is unaffected.
RENODE_I2C = {
    "st/i2c_v2": "I2C.STM32F7_I2C",  # the v2 IP alloy's STM32G0 chips declare
}

# Renode SPI CONTROLLER model per IP version — same rule again. Unlike the I2C
# model, SPI.STM32SPI exposes an `IRQ` line, so it is wired to the NVIC.
RENODE_SPI = {
    "st/spi_v2": "SPI.STM32SPI",
    "st/spi_v3": "SPI.STM32SPI",
}

# ADC is different: Renode ships only the F1/F4-style Analog.STM32_ADC, whose
# SR/CR1/CR2 register map is INCOMPATIBLE with alloy's st/adc_v2 (STM32G0-style
# ISR/CR/CHSELR — a local register trace showed the driver spinning on ISR.ADRDY
# that the F4 model never sets). So instead of a built-in model, emit a tiny
# purpose-written model as an inline Python peripheral (IronPython 2.7). It
# implements just the handshakes st_adc_v2 performs — ADCAL self-clears; ADEN
# sets ISR.ADRDY; CHSELR (1<<ch) sets ISR.CCRDY and latches the channel; ADSTART
# sets ISR.EOC and loads DR with a channel-ENCODED value (1000 + channel) so a
# read of channel N returns 1000+N (a wrong channel would return a wrong number,
# so a conformance test can't pass by coincidence); reading DR clears EOC.
_ADC_G0_MODEL = {"st/adc_v2"}
_ADC_G0_SCRIPT = """if request.IsInit:
    regs = [0] * (size / 4)
    sel = 0
elif request.IsWrite:
    o = request.Offset
    v = request.Value
    if o == 0x08:
        if v & (1 << 31): v = v & ~(1 << 31)
        if v & 0x1: regs[0] = regs[0] | 0x1
        if v & 0x4:
            regs[0] = regs[0] | 0x4
            regs[0x40 >> 2] = 1000 + sel
            v = v & ~0x4
        regs[2] = v
    elif o == 0x28:
        regs[0x28 >> 2] = v
        sel = 0
        m = v
        while m > 1:
            m = m >> 1
            sel = sel + 1
        regs[0] = regs[0] | (1 << 13)
    elif o == 0x00:
        regs[0] = regs[0] & ~v
    else:
        regs[o >> 2] = v
elif request.IsRead:
    o = request.Offset
    if o == 0x40:
        request.Value = regs[0x40 >> 2]
        regs[0] = regs[0] & ~0x4
    else:
        request.Value = regs[o >> 2]"""

# Cortex-M System Control Space / NVIC base. Architectural — identical on every
# Cortex-M, the same constant the hand-written arch layer uses (src/alloy/arch/),
# NOT a per-chip silicon fact. Kept as a named constant so the codegen carries no
# raw address.
_CORTEX_M_SCS_BASE = 0xE000E000  # contract-ok: architectural Cortex-M constant, not chip data


def _resolve(chip: dict[str, Any], board: dict[str, Any]):
    """Shared gate: returns (cpu, uart_name, periph, model, irq_number) or raises
    EmitError if this board/chip is not Renode-emulable."""
    arch = chip["cores"][0]["arch"]
    cpu = RENODE_CPU.get(arch)
    if cpu is None:
        raise EmitError(f"renode: no CPU mapping for arch '{arch}'")

    roles = board.get("roles") or board
    uart_role = roles.get("debug_uart")
    if not uart_role or "peripheral" not in uart_role:
        raise EmitError("renode: board has no debug_uart role to observe")
    name = uart_role["peripheral"]

    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        raise EmitError(f"renode: debug_uart peripheral '{name}' is not curated")
    model = RENODE_UART.get(periph.get("ip"))
    if model is None:
        raise EmitError(f"renode: no UART model for ip '{periph.get('ip')}'")

    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        raise EmitError(f"renode: debug_uart peripheral '{name}' has no mapped IRQ")
    return cpu, name, periph, model, irqn


def _resolve_i2c(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the I2C controller: returns (name, base, model, irq) if
    the board has a curated i2c role whose IP Renode models, else None. Never
    raises — I2C is an ADDITION to the platform, so a board without it just emits
    the CPU/UART platform unchanged."""
    roles = board.get("roles") or board
    role = roles.get("i2c")
    if not role or "peripheral" not in role:
        return None
    name = role["peripheral"]
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    model = RENODE_I2C.get(periph.get("ip"))
    if model is None:
        return None
    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        return None
    return name, int(periph["base"], 16), model, irqn


def _resolve_spi(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the SPI controller: returns (name, base, model, irq) if
    the board has a curated spi role whose IP Renode models, else None. Like
    _resolve_i2c, never raises — SPI is an addition to the platform."""
    roles = board.get("roles") or board
    role = roles.get("spi")
    if not role or "peripheral" not in role:
        return None
    name = role["peripheral"]
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    model = RENODE_SPI.get(periph.get("ip"))
    if model is None:
        return None
    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        return None
    return name, int(periph["base"], 16), model, irqn


def _resolve_adc(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the ADC. Returns (name, base) if the board has a curated
    adc role whose IP has a Renode model (the inline G0 Python model), else None."""
    roles = board.get("roles") or board
    role = roles.get("adc")
    name = role.get("peripheral") if isinstance(role, dict) else None
    if name is None:
        name = "adc1" if "adc1" in chip["peripherals"] else "adc"
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    if periph.get("ip") not in _ADC_G0_MODEL:
        return None
    return name, int(periph["base"], 16)


def renode_supported(chip: dict[str, Any], board: dict[str, Any]) -> bool:
    """True if this board can be emulated (used to gate the CI matrix)."""
    try:
        _resolve(chip, board)
    except EmitError:
        return False
    return True


def debug_uart_name(chip: dict[str, Any], board: dict[str, Any]) -> str:
    return _resolve(chip, board)[1]


def _mem(chip: dict[str, Any], kind: str) -> dict[str, Any]:
    m = next((m for m in chip["memories"] if m["kind"] == kind), None)
    if m is None:
        raise EmitError(f"renode: chip has no '{kind}' memory")
    return m


def emit_renode_platform(chip: dict[str, Any], board: dict[str, Any]) -> str:
    """The .repl: a minimal but faithful platform — CPU, NVIC, flash, SRAM and
    the debug UART, all addressed from chip data."""
    cpu, name, periph, model, irqn = _resolve(chip, board)
    flash = _mem(chip, "flash")
    ram = _mem(chip, "ram")
    base = int(periph["base"], 16)
    uart_clock = _UART_CLOCK_PROP.get(model, "frequency")
    platform = f"""{_REPL_BANNER}// {chip['vendor']}/{chip['part']} — minimal platform for headless CI emulation.

cpu: CPU.CortexM @ sysbus
    cpuType: "{cpu}"
    nvic: nvic

nvic: IRQControllers.NVIC @ sysbus {_CORTEX_M_SCS_BASE:#010x}
    priorityMask: 0xF0
    systickFrequency: 8000000
    IRQ -> cpu@0

flash: Memory.MappedMemory @ sysbus {flash['base']}
    size: {int(flash['size']):#x}

sram: Memory.MappedMemory @ sysbus {ram['base']}
    size: {int(ram['size']):#x}

{name}: {model} @ sysbus {base:#010x}
    {uart_clock}: 8000000
    IRQ -> nvic@{irqn}
"""
    i2c = _resolve_i2c(chip, board)
    if i2c is not None:
        i2c_name, i2c_base, i2c_model, _ = i2c
        # No interrupt line: I2C.STM32F7_I2C exposes EventInterrupt/ErrorInterrupt
        # (not the UART's `IRQ`), and on real STM32G0 they route through EXTI,
        # which this minimal platform omits. alloy's I2C driver is polling
        # (bounded-spin on the status register), so the controller works for
        # probe/read/write with no interrupt wired — and an unconnected model is
        # inert for the boot/UART legs that share this platform.
        platform += f"""
{i2c_name}: {i2c_model} @ sysbus {i2c_base:#010x}
"""
    spi = _resolve_spi(chip, board)
    if spi is not None:
        spi_name, spi_base, spi_model, spi_irq = spi
        # SPI.STM32SPI has an IRQ line (unlike the I2C model), wired to the NVIC.
        # Its `series` ctor param is optional on the pinned Renode 1.16.1 (it
        # became REQUIRED on renode-latest nightly — see the pinned-version note in
        # ci.yml), so no series is emitted. Real silicon added to the platform; a
        # test attaches an SPI slave device at runtime.
        platform += f"""
{spi_name}: {spi_model} @ sysbus {spi_base:#010x}
    IRQ -> nvic@{spi_irq}
"""
    adc = _resolve_adc(chip, board)
    if adc is not None:
        adc_name, adc_base = adc
        # Renode has no STM32G0 ADC model, so emit a tiny purpose-written one as an
        # inline Python peripheral (see _ADC_G0_SCRIPT). The script sits inside a
        # `'''…'''` block at column 0, exactly like Renode's own vegaboard.repl.
        platform += f"""
{adc_name}: Python.PythonPeripheral @ sysbus {adc_base:#010x}
    size: 0x400
    initable: true
    script: '''
{_ADC_G0_SCRIPT}
'''
"""
    # (DMA/PWM conformance stays out: st/dma_v1's only example rides the ADC burst,
    # and PWM has no UART-observable output. See [[alloy-audit-2026-07]].)
    return platform


def emit_renode_script(chip: dict[str, Any], board: dict[str, Any],
                       repl_path: str, elf_path: str) -> str:
    """The .resc: build the machine and load the ELF, but do NOT start — the
    caller (alloy emulate, or the CI Robot test) attaches a UART observer and
    then starts, so no early output is missed.

    Renode's monitor cannot tokenize an `@`-path containing spaces, but nested
    `@`-paths inside an included .resc are only resolved relative to the runner's
    working directory (renode-test doesn't resolve them relative to the .resc).
    So: use ABSOLUTE paths when they are space-free — unambiguous for any cwd,
    which is what the CI Robot runner needs — and fall back to BARE filenames
    only when the path contains spaces, in which case the caller must run Renode
    with the .resc's own directory as the working directory (alloy emulate does).
    A repo dir like ".../01 - Codes/..." is the case that forces the bare form."""
    name = _resolve(chip, board)[1]
    space_free = " " not in repl_path and " " not in elf_path
    repl_ref = repl_path if space_free else Path(repl_path).name
    elf_ref = elf_path if space_free else Path(elf_path).name
    return f"""{_RESC_BANNER}# Headless machine for {board['id']}: platform is generated from chip data.
using sysbus
mach create "{board['id']}"
machine LoadPlatformDescription @{repl_ref}
sysbus LoadELF @{elf_ref}
# No `start` here: `alloy emulate` adds `showAnalyzer {name}; start`; the CI
# Robot test attaches a terminal tester to `{name}` first, then starts.
"""
