"""Emit a Renode platform (.repl) + run script (.resc) so CI can EXECUTE
firmware, not just compile it.

The platform is data-driven from the SAME chip/board facts the linker and vector
table consume — CPU, memory map and the debug UART's address/IRQ all come from
alloy-devices, so the emulated target cannot drift from the real one and nothing
here is a hand-maintained silicon fact (guard #1: facts are generated).

Renode's SoC coverage is uneven, so RENODE_CPU / RENODE_UART gate emulation to
the families Renode models well (keyed like debug.py's OPENOCD_TARGET — tool
integration, not silicon facts). An unsupported family raises EmitError and is
simply left out of the emulation matrix. Emulation is an ADDITIONAL honesty gate
("does uart_echo actually boot and print its banner?"), never a substitute for
on-silicon validation.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .common import EmitError

_REPL_BANNER = "// GENERATED by alloy — DO NOT EDIT (fix the data or the emitter and regenerate)\n"
_RESC_BANNER = "# GENERATED by alloy — DO NOT EDIT (fix the data or the emitter and regenerate)\n"

# Cortex-M core arch -> Renode cpuType.
RENODE_CPU = {
    "armv6m": "cortex-m0",
    "armv7m": "cortex-m3",
    "armv7em": "cortex-m7",
    "armv8m_base": "cortex-m23",
    "armv8m_main": "cortex-m33",
    # xtensa_lx6 (ESP32) intentionally absent: Renode Xtensa support is out of scope.
}

# Renode UART peripheral model per debug-UART IP version. Only IPs whose register
# layout Renode models compatibly are listed; a board whose debug UART is absent
# here is left out of the emulation matrix rather than emulated incorrectly.
RENODE_UART = {
    "st/usart_v2": "UART.STM32F7_USART",
    "st/usart_v3": "UART.STM32F7_USART",
    "st/usart_v4": "UART.STM32F7_USART",
    "raspberrypi/uart_pl011": "UART.PL011",
    "microchip/usart_v1": "UART.SAM_USART",  # SAME70/SAMV71 USART (Cortex-M7)
}

# The .repl property that feeds a UART model its input clock. Most Renode UART
# models name it `frequency`; SAM_USART's constructor parameter is `clockFrequency`
# and Renode rejects the platform (E25: no suitable constructor) if the name is
# wrong. The VALUE is immaterial to the headless terminal tester — it reads a
# logical byte stream, not a real baud rate — but the NAME must match the model.
_UART_CLOCK_PROP = {
    "UART.SAM_USART": "clockFrequency",
}

# Renode I2C CONTROLLER model per IP version — same idea as RENODE_UART, and the
# same honesty rule: only IPs whose register layout Renode models compatibly are
# listed. This adds the real silicon controller to the emulated platform (a
# faithful, data-driven addition); the DummyI2CSlave a conformance test needs is a
# TEST FIXTURE the Robot attaches at runtime, not something the platform emitter
# bakes in. A board without a curated i2c role, or whose i2c IP is absent here,
# simply gets no I2C block — the rest of the platform is unaffected.
RENODE_I2C = {
    "st/i2c_v2": "I2C.STM32F7_I2C",  # the v2 IP alloy's STM32G0 chips declare
    # The v1 IP (STM32F1/F4 SR1/SR2/CR1/CR2 layout) that all 149 F4 chips
    # declare. Renode ships I2C.STM32F4_I2C, a model written for exactly this
    # controller, and stm32f4.repl instantiates it at all three F411 bases. The
    # F4 I2C driver is labelled "tier-2, compile-checked" only because no F4
    # board exists yet — the emulation half is available the moment one does.
    "st/i2c_v1": "I2C.STM32F4_I2C",
}

# Renode SPI CONTROLLER model per IP version — same rule again. Unlike the I2C
# model, SPI.STM32SPI exposes an `IRQ` line, so it is wired to the NVIC.
RENODE_SPI = {
    "st/spi_v1": "SPI.STM32SPI",  # the F1/F4 IP — same model, same reason as i2c_v1
    "st/spi_v2": "SPI.STM32SPI",
    "st/spi_v3": "SPI.STM32SPI",
}

# Renode PIN-INTERRUPT controller model per IP version — the block that turns a
# GPIO edge into an NVIC interrupt. The model named here is NOT the one Renode's
# own platforms/cpus/stm32g0.repl uses: that file instantiates
# IRQControllers.STM32F4_EXTI at the G0's EXTI base under its own comment "This
# model's registers are not compatible with the EXTI in this MCU", and it is
# right — the F4 model is IMR/EMR/RTSR/FTSR/SWIER/PR at 0x00-0x14, while the G0
# (alloy's st/exti_g0) is RTSR1 0x00 / FTSR1 0x04 / SWIER1 0x08 / RPR1 0x0C /
# FPR1 0x10 / EXTICR 0x60 / IMR1 0x80. STM32WBA_EXTI's register map matches the
# G0's byte for byte, so it is used here on register-map equivalence — the same
# substitution the I2C/flash entries above make (I2C.STM32F4_I2C, MTD.
# STM32F4_FlashController). Verified by RUNNING it, not by reading: see the
# emission block below for what the emulation does and does not prove.
RENODE_EXTI = {
    "st/exti_g0": "IRQControllers.STM32WBA_EXTI",
}

# ADC is different. The F1/F4-style Analog.STM32_ADC has an SR/CR1/CR2 register
# map INCOMPATIBLE with alloy's st/adc_v2 (STM32G0-style ISR/CR/CHSELR — a local
# register trace showed the driver spinning on an ISR.ADRDY the F4 model never
# sets). Renode 1.16.1 DOES also ship Analog.STM32G0_ADC, and its own
# platforms/cpus/stm32g0.repl instantiates it at the G0's ADC base — an earlier
# version of this comment claimed no G0 model existed, which is wrong. Swapping
# was tried and the firmware did not complete its handshake against it (the run
# hung rather than failing cleanly), so the diagnosis is unfinished and the
# purpose-written model below stays for now. Adopting the native model would
# make this leg an INDEPENDENT check instead of a consistency one, and is worth
# finishing. Until then, emit a tiny
# purpose-written model as an inline Python peripheral (IronPython 2.7). It
# implements just the handshakes st_adc_v2 performs — ADCAL self-clears; ADEN
# sets ISR.ADRDY; CHSELR (1<<ch) sets ISR.CCRDY and latches the channel; ADSTART
# sets ISR.EOC and loads DR with a channel-ENCODED value (1000 + channel) so a
# read of channel N returns 1000+N (a wrong channel would return a wrong number,
# so a conformance test can't pass by coincidence); reading DR clears EOC.
# Independent watchdog: Renode models the ST IWDG faithfully (down-counter off
# LSI; timeout resets the machine). frequency must match the LSI the HAL's tick
# math assumes (st_iwdg_detail: iwdg_lsi_hz = 32000). Inert until the firmware
# starts it, so it's safe in every leg's platform; the OTA trial/rollback E2E is
# what actually exercises it (a never-feeding trial image self-resets).
RENODE_WDG = {
    "st/iwdg_v2": "Timers.STM32_IndependentWatchdog",
}

_ADC_G0_MODEL = {"st/adc_v2"}
_ADC_G0_SCRIPT = """if request.IsInit:
    regs = [0] * (size / 4)
    sel = 0
elif request.IsWrite:
    o = request.Offset
    v = request.Value
    if o == 0x08:
        if v & (1 << 31): v = v & ~(1 << 31)
        if v & 0x1: regs[0] = regs[0] | 0x1
        if v & 0x4:
            regs[0] = regs[0] | 0x4
            regs[0x40 >> 2] = 1000 + sel
            v = v & ~0x4
        regs[2] = v
    elif o == 0x28:
        regs[0x28 >> 2] = v
        sel = 0
        m = v
        while m > 1:
            m = m >> 1
            sel = sel + 1
        regs[0] = regs[0] | (1 << 13)
    elif o == 0x00:
        regs[0] = regs[0] & ~v
    else:
        regs[o >> 2] = v
elif request.IsRead:
    o = request.Offset
    if o == 0x40:
        request.Value = regs[0x40 >> 2]
        regs[0] = regs[0] & ~0x4
    else:
        request.Value = regs[o >> 2]"""

# DMA uses Renode's OWN DMA.STM32G0DMA (see the block that emits it). This
# file used to carry a ~40-line inline Python model of the channel-style
# controller, justified by a comment claiming Renode had none; it does, and
# its own stm32g0.repl wires two of them. The native model passes the same
# dma_uart leg, so the hand-written one is gone: a model this project wrote
# cannot falsify a misreading of the reference manual that it shares with the
# driver, and this one additionally had no NVIC connection, which made every
# interrupt-driven DMA path untestable.
_DMA_G0_MODEL = {"st/dma_v1"}


# Cortex-M System Control Space / NVIC base. Architectural — identical on every
# Cortex-M, the same constant the hand-written arch layer uses (src/alloy/arch/),
# NOT a per-chip silicon fact. Kept as a named constant so the codegen carries no
# raw address.
_CORTEX_M_SCS_BASE = 0xE000E000  # contract-ok: architectural Cortex-M constant, not chip data


def _resolve(chip: dict[str, Any], board: dict[str, Any]):
    """Shared gate: returns (cpu, uart_name, periph, model, irq_number) or raises
    EmitError if this board/chip is not Renode-emulable."""
    arch = chip["cores"][0]["arch"]
    cpu = RENODE_CPU.get(arch)
    if cpu is None:
        raise EmitError(f"renode: no CPU mapping for arch '{arch}'")

    roles = board.get("roles") or board
    uart_role = roles.get("debug_uart")
    if not uart_role or "peripheral" not in uart_role:
        raise EmitError("renode: board has no debug_uart role to observe")
    name = uart_role["peripheral"]

    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        raise EmitError(f"renode: debug_uart peripheral '{name}' is not curated")
    model = RENODE_UART.get(periph.get("ip"))
    if model is None:
        raise EmitError(f"renode: no UART model for ip '{periph.get('ip')}'")

    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        raise EmitError(f"renode: debug_uart peripheral '{name}' has no mapped IRQ")
    return cpu, name, periph, model, irqn


def _resolve_i2c(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the I2C controller: returns (name, base, model, irq) if
    the board has a curated i2c role whose IP Renode models, else None. Never
    raises — I2C is an ADDITION to the platform, so a board without it just emits
    the CPU/UART platform unchanged."""
    roles = board.get("roles") or board
    role = roles.get("i2c")
    if not role or "peripheral" not in role:
        return None
    name = role["peripheral"]
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    model = RENODE_I2C.get(periph.get("ip"))
    if model is None:
        return None
    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        return None
    return name, int(periph["base"], 16), model, irqn


def _resolve_spi(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the SPI controller: returns (name, base, model, irq) if
    the board has a curated spi role whose IP Renode models, else None. Like
    _resolve_i2c, never raises — SPI is an addition to the platform."""
    roles = board.get("roles") or board
    role = roles.get("spi")
    if not role or "peripheral" not in role:
        return None
    name = role["peripheral"]
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    model = RENODE_SPI.get(periph.get("ip"))
    if model is None:
        return None
    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    irqn = irqs.get(periph.get("irq"))
    if irqn is None:
        return None
    return name, int(periph["base"], 16), model, irqn


def _resolve_adc(chip: dict[str, Any], board: dict[str, Any]):
    """Optional gate for the ADC. Returns (name, base) if the board has a curated
    adc role whose IP has a Renode model (the inline G0 Python model), else None."""
    roles = board.get("roles") or board
    role = roles.get("adc")
    name = role.get("peripheral") if isinstance(role, dict) else None
    if name is None:
        name = "adc1" if "adc1" in chip["peripherals"] else "adc"
    periph = chip["peripherals"].get(name)
    if periph is None or periph.get("uncurated"):
        return None
    if periph.get("ip") not in _ADC_G0_MODEL:
        return None
    return name, int(periph["base"], 16)


def _resolve_wdg(chip: dict[str, Any]):
    """The independent watchdog, if the chip declares one Renode models."""
    periph = chip.get("peripherals", {}).get("iwdg")
    if periph and not periph.get("uncurated") and periph.get("ip") in RENODE_WDG:
        return "iwdg", int(periph["base"], 16), RENODE_WDG[periph["ip"]]
    return None


def _resolve_dma(chip: dict[str, Any]):
    """The DMA1 controller if it's the st/dma_v1 (G0) IP, with the channel count
    and NVIC lines the platform needs. DMA is a capability, not a pin-routed
    board role, so this keys straight off the chip peripheral."""
    for name in ("dma1", "dma"):
        periph = chip["peripherals"].get(name)
        if periph and not periph.get("uncurated") and periph.get("ip") in _DMA_G0_MODEL:
            ch = periph.get("channels") or {}
            if not all(k in ch for k in ("count", "irqline1", "irqline2_3", "irqline4_7")):
                return None  # data too thin to wire interrupts: emit nothing
            return name, int(periph["base"], 16), ch
    return None


def _renode_lines(lo: int, hi: int) -> str:
    """Renode's connection-index syntax for an inclusive range: a bare index, a
    comma pair, or a dash range — the three forms Renode's own .repl files use."""
    if lo == hi:
        return str(lo)
    if hi - lo == 1:
        return f"[{lo}, {hi}]"
    return f"[{lo}-{hi}]"


def _resolve_exti(chip: dict[str, Any]):
    """Optional gate for the pin-interrupt controller. Returns
    (name, base, model, groups, ports, aperture) or None. Never raises — EXTI is
    an ADDITION to the platform, so a chip without the data emits nothing extra.

    Everything here is a chip fact:
      * which peripheral      — the one whose `ip` has a Renode model;
      * which NVIC vector each line raises — its `irq_lines` groups;
      * which ports exist and what value routes them — every curated peripheral
        carrying `port_index` (the EXTICR port code, which is NOT the port's
        alphabetical position: a die with no port E leaves a hole at 4);
      * how wide a port's register aperture is — the smallest gap between two
        port bases, so no address-map constant is hand-written here.
    A chip missing any of it simply gets no EXTI block, exactly like every other
    optional peripheral above."""
    exti = next(
        ((n, p) for n, p in sorted(chip.get("peripherals", {}).items())
         if not p.get("uncurated") and p.get("ip") in RENODE_EXTI),
        None,
    )
    if exti is None:
        return None
    name, periph = exti
    groups = periph.get("irq_lines")
    if not groups:
        return None
    irqs = {i["name"]: i["number"] for i in chip.get("interrupts", [])}
    if any(g["irq"] not in irqs for g in groups):
        return None
    ports = sorted(
        (int(p["port_index"]), pname, int(p["base"], 16))
        for pname, p in chip.get("peripherals", {}).items()
        if not p.get("uncurated") and "port_index" in p
    )
    if len(ports) < 2:
        return None
    bases = sorted(b for _, _, b in ports)
    aperture = min(b - a for a, b in zip(bases, bases[1:]) if b > a)
    resolved = [(g["irq"], irqs[g["irq"]], int(g["first"]), int(g["last"]))
                for g in sorted(groups, key=lambda g: g["first"])]
    base = int(periph["base"], 16)
    return (name, base, RENODE_EXTI[periph["ip"]], resolved, ports, aperture,
            _window(chip, base))


def _window(chip: dict[str, Any], base: int) -> int:
    """How far a peripheral placed at `base` may reach: up to its next
    neighbour, never into it.

    Renode takes the size from the MODEL when a line gives none, and a model
    written for another die can claim far more than the real block. That is not
    hypothetical: STM32WBA_EXTI claims at least 4K, so an unbounded `exti` at
    the G0's 0x40021800 swallowed the flash controller at 0x40022000 — every
    FLASH_SR/FLASH_CR access landed inside EXTI and was logged as an unhandled
    offset 0x810/0x814 instead of reaching (or visibly missing) its own block.

    The bound is a fact, not a constant: the gap to the next peripheral this
    chip declares. Same technique as the GPIO aperture above, and it adapts to a
    die that packs its blocks differently.
    """
    higher = sorted(
        int(p["base"], 16) for p in (chip.get("peripherals") or {}).values()
        if p.get("base") and int(p["base"], 16) > base
    )
    # No neighbour above: the architectural 4K page is the conservative answer.
    return (higher[0] - base) if higher else 0x1000


def renode_supported(chip: dict[str, Any], board: dict[str, Any]) -> bool:
    """True if this board can be emulated (used to gate the CI matrix)."""
    try:
        _resolve(chip, board)
    except EmitError:
        return False
    return True


def debug_uart_name(chip: dict[str, Any], board: dict[str, Any]) -> str:
    return _resolve(chip, board)[1]


def _mem(chip: dict[str, Any], kind: str) -> dict[str, Any]:
    m = next((m for m in chip["memories"] if m["kind"] == kind), None)
    if m is None:
        raise EmitError(f"renode: chip has no '{kind}' memory")
    return m


def emit_renode_platform(chip: dict[str, Any], board: dict[str, Any]) -> str:
    """The .repl: a minimal but faithful platform — CPU, NVIC, flash, SRAM and
    the debug UART, all addressed from chip data."""
    cpu, name, periph, model, irqn = _resolve(chip, board)
    flash = _mem(chip, "flash")
    ram = _mem(chip, "ram")
    base = int(periph["base"], 16)
    uart_clock = _UART_CLOCK_PROP.get(model, "frequency")
    platform = f"""{_REPL_BANNER}// {chip['vendor']}/{chip['part']} — minimal platform for headless CI emulation.

cpu: CPU.CortexM @ sysbus
    cpuType: "{cpu}"
    nvic: nvic

nvic: IRQControllers.NVIC @ sysbus {_CORTEX_M_SCS_BASE:#010x}
    priorityMask: 0xF0
    systickFrequency: 8000000
    IRQ -> cpu@0

flash: Memory.MappedMemory @ sysbus {flash['base']}
    size: {int(flash['size']):#x}

sram: Memory.MappedMemory @ sysbus {ram['base']}
    size: {int(ram['size']):#x}

{name}: {model} @ sysbus {base:#010x}
    {uart_clock}: 8000000
    IRQ -> nvic@{irqn}
"""
    i2c = _resolve_i2c(chip, board)
    if i2c is not None:
        i2c_name, i2c_base, i2c_model, i2c_irq = i2c
        # I2C.STM32F7_I2C names its event line `EventInterrupt`, not the UART
        # model's `IRQ` — hence the different sink name here. It goes STRAIGHT to
        # the NVIC. Renode's own stm32g0.repl sends it to exti@23 instead, which
        # used to read as "the interrupt needs an EXTI this platform omits", but
        # that EXTI is above `firstDirectLine: 19` and its only job for line 23 is
        # `[23] -> nvic@[23]` — an unconfigured pass-through. Wiring the model's
        # line directly at the same NVIC number is equivalent and needs no EXTI.
        # Verified by running it, not reasoned about: with this line the i2c_read
        # leg's completion-callback assertion passes, and without it the same
        # firmware fails that assertion.
        #
        # `ErrorInterrupt` (BERR/ARLO/OVR) is left unwired: no driver in the tree
        # arms ERRIE, so wiring a line nothing enables would emit a claim the
        # firmware does not make.
        platform += f"""
{i2c_name}: {i2c_model} @ sysbus {i2c_base:#010x}
    EventInterrupt -> nvic@{i2c_irq}
"""
    spi = _resolve_spi(chip, board)
    if spi is not None:
        spi_name, spi_base, spi_model, spi_irq = spi
        # SPI.STM32SPI has an IRQ line (unlike the I2C model), wired to the NVIC.
        # Its `series` ctor param is optional on the pinned Renode 1.16.1 (it
        # became REQUIRED on renode-latest nightly — see the pinned-version note in
        # ci.yml), so no series is emitted. Real silicon added to the platform; a
        # test attaches an SPI slave device at runtime.
        platform += f"""
{spi_name}: {spi_model} @ sysbus {spi_base:#010x}
    IRQ -> nvic@{spi_irq}
"""
    adc = _resolve_adc(chip, board)
    if adc is not None:
        adc_name, adc_base = adc
        # Renode has no STM32G0 ADC model, so emit a tiny purpose-written one as an
        # inline Python peripheral (see _ADC_G0_SCRIPT). The script sits inside a
        # `'''…'''` block at column 0, exactly like Renode's own vegaboard.repl.
        platform += f"""
{adc_name}: Python.PythonPeripheral @ sysbus {adc_base:#010x}
    size: 0x400
    initable: true
    script: '''
{_ADC_G0_SCRIPT}
'''
"""
    dma = _resolve_dma(chip)
    if dma is not None:
        dma_name, dma_base, dma_ch = dma
        count = int(dma_ch["count"])
        line1 = int(dma_ch["irqline1"])
        line23 = int(dma_ch["irqline2_3"])
        line47 = int(dma_ch["irqline4_7"])
        # Channels 2..N share NVIC lines (RM0444: ch1 alone, ch2-3 together,
        # ch4-7 together), and Renode needs an explicit OR gate per shared line
        # — a peripheral cannot drive an NVIC input two channels also drive.
        # Renode indexes channels from 0, so channel N is index N-1.
        rest = count - 3  # channels 4..N
        platform += f"""
nvicInput{line23}: Miscellaneous.CombinedInput @ none
    numberOfInputs: 2
    -> nvic@{line23}

nvicInput{line47}: Miscellaneous.CombinedInput @ none
    numberOfInputs: {rest}
    -> nvic@{line47}

{dma_name}: DMA.STM32G0DMA @ sysbus {dma_base:#010x}
    numberOfChannels: {count}
    0 -> nvic@{line1}
    [1, 2] -> nvicInput{line23}@[0, 1]
    [3-{count - 1}] -> nvicInput{line47}@[0-{rest - 1}]
"""
    exti = _resolve_exti(chip)
    if exti is not None:
        (exti_name, exti_base, exti_model, exti_groups, exti_ports, exti_ap,
         exti_win) = exti
        # A pin edge only reaches the CPU if THREE things are modelled: the GPIO
        # port that sources it, the EXTI that selects and latches it, and the OR
        # gates that merge EXTI's per-line outputs onto the few NVIC vectors the
        # die actually has. All three are emitted here, none of the numbers are
        # written down: the vectors come from `irq_lines`, the port routing value
        # from each port's `port_index`, the aperture from the port bases.
        #
        # Renode needs an explicit CombinedInput per SHARED vector for the same
        # reason the DMA block above does — a peripheral cannot drive an NVIC
        # input another line also drives.
        #
        # A port reaches EXTI through a CONNECTION GROUP, `exti#<port_index>`,
        # and the model honours EXTICR: an edge on a port the firmware did not
        # select is dropped. Indexing by port_index (not by a dense counter over
        # the ports this die has) is what makes that correct on a die with a hole
        # in its port numbering.
        #
        # WHAT THE EMULATION DOES AND DOES NOT PROVE. Every line below was
        # MEASURED on Renode 1.16.1 with a throwaway G0 firmware and monitor
        # register probes, each with a matched negative control. None of it is
        # inferred from the model's source or its register names.
        # PROVEN by emulation:
        #  * EXTICR routing — an edge injected on a port the firmware did not
        #    select in EXTICR does not fire (control: OnGPIO on gpioa while
        #    EXTICR selects port C -> the firmware prints its NOT-fired line).
        #  * RTSR1/FTSR1 trigger selection — arming only RTSR1 fires on a rising
        #    input and not on a falling one, and vice versa.
        #  * NVIC delivery through the GROUPED vector, hence `irq_lines` itself
        #    (control: rewire lines 4-15 to vector 6 and the same firmware, still
        #    listening on 7, never fires).
        #  * That pending MUST be cleared — with no clear at all the EXTI output
        #    stays asserted and the NVIC re-latches immediately (ISPR reads back
        #    set right after ICPR clears it), and the firmware makes no further
        #    progress. The trap this project has hit twice is real here.
        # NOT proven — three model divergences a driver must not be validated on:
        #  * IMR1 is unimplemented for the configurable lines. Writing bit n of
        #    offset 0x80 logs "Unhandled write to offset 0x80", reads back 0, and
        #    the interrupt fires anyway (EMR1 at 0x84 behaves the same). A driver
        #    that never unmasks still passes here; only silicon can check that.
        #  * The PENDING HALVES ARE NOT FAITHFUL. On a G0, a rising edge sets
        #    RPR1 (0x0C) and a falling edge FPR1 (0x10). This model puts BOTH
        #    into 0x10 — measured: rising-armed + rising input leaves 0x0C at 0
        #    and 0x10 at the line bit — and it deasserts the output on a write to
        #    EITHER register. So emulation cannot check that a handler clears the
        #    right half, and a handler that reports edge DIRECTION from these two
        #    registers will report "falling" for every edge under Renode.
        #  * SWIER1 (0x08) throws a NullReferenceException inside the model and
        #    takes Renode down — reproduced from a bare monitor write with no ELF
        #    loaded. Nothing in emulation may software-trigger a line.
        # No modeResetValue / pullUpPullDownResetValue / numberOfAFs is emitted:
        # the model's defaults leave every pin an input, which is what an edge
        # needs, and those values are per-die facts (Renode's own stm32g0.repl
        # writes numberOfAFs: 8 and two 8-digit reset masks) that would be
        # hand-written silicon in a generator. The AF-count default is the
        # permissive one, so a real AF write still lands.
        for _irq_name, irqn, first, last in exti_groups:
            if last > first:
                platform += f"""
nvicInput{irqn}: Miscellaneous.CombinedInput @ none
    numberOfInputs: {last - first + 1}
    -> nvic@{irqn}
"""
        conns = "\n".join(
            f"    {_renode_lines(first, last)} -> "
            + (f"nvicInput{irqn}@{_renode_lines(0, last - first)}" if last > first
               else f"nvic@{irqn}")
            for _irq_name, irqn, first, last in exti_groups
        )
        platform += f"""
{exti_name}: {exti_model} @ sysbus <{exti_base:#010x}, +{exti_win:#x}>
    numberOfOutputLines: {max(g[3] for g in exti_groups) + 1}
{conns}
"""
        for port_index, port_name, port_base in exti_ports:
            platform += f"""
{port_name}: GPIOPort.STM32_GPIOPort @ sysbus <{port_base:#010x}, +{exti_ap:#x}>
    [0-15] -> {exti_name}#{port_index}@[0-15]
"""
    # Flash controller: only for IPs Renode models faithfully. MTD's F4 model
    # covers the F7 (same CR/SR + sector map at each size) and services REAL
    # sector erases against the MappedMemory — so an F7 bootloader's slot erase
    # is genuinely modeled, not a no-op. G0 stays without a controller model on
    # purpose (its legs are green on direct memory writes; do not disturb).
    fc = chip.get("peripherals", {}).get("flash")
    if fc and not fc.get("uncurated") and fc.get("ip") == "st/flash_f7":
        platform += f"""
flash_ctrl: MTD.STM32F4_FlashController @ sysbus {int(fc["base"], 16):#010x}
    flash: flash
"""
    # SAME70 EEFC: Renode ships no EFC model, so emit a purpose-written one (the
    # ADC/DMA technique). It is deliberately FAITHFUL where a stub would lie:
    # FCR commands are refused without the 0x5A key (FSR.FCMDE, clear-on-read),
    # EPA performs the REAL 4/8/16/32-page erase against the memory through the
    # system bus (wrong FARG block math would visibly eat neighbours), and FMR
    # passes through for the clock program's wait-state write. WP is accepted
    # after key validation — page-latch content itself can't be modelled over a
    # MappedMemory (writes land directly), which is exactly why the driver's ECC
    # row-once discipline is enforced by construction in microchip_efc_v1.hpp,
    # not claimed as emulation-proven.
    efc = chip.get("peripherals", {}).get("efc")
    if efc and not efc.get("uncurated") and efc.get("ip") == "microchip/efc_v1":
        flash_mem = next(m for m in chip["memories"] if m["kind"] == "flash")
        fb = int(flash_mem["base"], 16) if isinstance(flash_mem["base"], str) else int(flash_mem["base"])
        platform += f"""
efc: Python.PythonPeripheral @ sysbus {int(efc["base"], 16):#010x}
    size: 0x200
    initable: true
    script: '''
if request.IsInit:
    fmr = 0
    fsr = 1
    membus = emulationManager.Instance.CurrentEmulation.Machines[0].SystemBus
elif request.IsWrite:
    o = request.Offset
    v = request.Value
    if o == 0x0:
        fmr = v
    elif o == 0x4:
        if ((v >> 24) & 0xFF) != 0x5A:
            fsr = fsr | 2
        else:
            cmd = v & 0xFF
            arg = (v >> 8) & 0xFFFF
            if cmd == 0x07:
                count = (4, 8, 16, 32)[arg & 3]
                first = arg & ~(count - 1)
                base = {fb:#x} + first * 512
                ones = (1 << 64) - 1
                i = 0
                while i < count * 512:
                    membus.WriteQuadWord(base + i, ones)
                    i = i + 8
elif request.IsRead:
    o = request.Offset
    if o == 0x0:
        request.Value = fmr
    elif o == 0x8:
        request.Value = fsr
        fsr = 1
    else:
        request.Value = 0
'''
"""
    wdg = _resolve_wdg(chip)
    if wdg is not None:
        wdg_name, wdg_base, wdg_model = wdg
        # frequency = the LSI the HAL's timeout math assumes (iwdg_lsi_hz).
        platform += f"""
{wdg_name}: {wdg_model} @ sysbus {wdg_base:#010x}
    frequency: 32000
"""
    # (PWM conformance stays out: it has no UART-observable output — it drives a
    # timer/GPIO. See [[alloy-audit-2026-07]].)
    return platform


def emit_renode_script(chip: dict[str, Any], board: dict[str, Any],
                       repl_path: str, elf_path: str) -> str:
    """The .resc: build the machine and load the ELF, but do NOT start — the
    caller (alloy emulate, or the CI Robot test) attaches a UART observer and
    then starts, so no early output is missed.

    Renode's monitor cannot tokenize an `@`-path containing spaces, but nested
    `@`-paths inside an included .resc are only resolved relative to the runner's
    working directory (renode-test doesn't resolve them relative to the .resc).
    So: use ABSOLUTE paths when they are space-free — unambiguous for any cwd,
    which is what the CI Robot runner needs — and fall back to BARE filenames
    only when the path contains spaces, in which case the caller must run Renode
    with the .resc's own directory as the working directory (alloy emulate does).
    A repo dir like ".../01 - Codes/..." is the case that forces the bare form."""
    name = _resolve(chip, board)[1]
    space_free = " " not in repl_path and " " not in elf_path
    repl_ref = repl_path if space_free else Path(repl_path).name
    elf_ref = elf_path if space_free else Path(elf_path).name
    # The ELF is loaded through a registered `macro reset`, not a bare LoadELF:
    # when the firmware resets itself (SYSRESETREQ from the fault handler, or a
    # watchdog), Renode pauses the machine and runs the machine's `reset` macro
    # to re-prepare it. With no macro registered it logs "No action for reset"
    # and stays paused FOREVER — in CI that is indistinguishable from a hang.
    # The macro re-runs LoadELF, which rewrites only the flash LOAD segments
    # (RAM keeps its contents, which is what lets a .noinit crash record
    # survive into the next boot), then the CPU re-inits PC/SP from the ELF —
    # a clean warm reboot, observed as a fresh banner on the UART. This is the
    # same pattern the OTA update lifecycle harness uses.
    return f"""{_RESC_BANNER}# Headless machine for {board['id']}: platform is generated from chip data.
using sysbus
mach create "{board['id']}"
machine LoadPlatformDescription @{repl_ref}
macro reset
\"\"\"
    sysbus LoadELF @{elf_ref}
\"\"\"
runMacro $reset
# No `start` here: `alloy emulate` adds `showAnalyzer {name}; start`; the CI
# Robot test attaches a terminal tester to `{name}` first, then starts.
"""
