"""A/B firmware-slot layout, derived from chip data.

The OTA core (src/alloy/ota/) is deliberately board-free: updater/boot_state work
on `slot{base,size}` values someone else provides. This module is that someone —
it partitions the chip's internal flash into

    [bootloader][slot A][slot B][boot-state store]

using only facts already in the database (flash base/size, and the flash
controller's page size keyed off its IP — the same honesty rule as the Renode
model maps: an IP absent from _FLASH_PAGE_SIZE simply has no slot layout, it is
never guessed). Everything is page-aligned so erase operations never straddle a
region boundary.

The app is linked INSIDE its slot at a fixed offset: the updater streams
[image_header(32) | payload] into the slot, and the payload's first bytes are
padding up to APP_OFFSET so the vector table lands at slot_base + APP_OFFSET —
512 B keeps any Cortex-M VTOR alignment requirement (largest vector count in the
matrix rounds to 512) while wasting less than a page.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .common import EmitError

_BANNER = "// GENERATED by alloy — DO NOT EDIT (fix the data or the emitter and regenerate)\n"

# Erase-page size per flash-controller IP. Fixed by the IP, not the part (all
# STM32G0 = 2 KB pages), so it lives here as an IP fact rather than being
# duplicated into every chip yaml.
_FLASH_PAGE_SIZE = {
    "st/flash_g0": 2048,
    # SAME70 EEFC: 512-byte program pages, erased in 16-page blocks — the erase
    # block is the layout's "page".
    "microchip/efc_v1": 8192,
}

# Vector table offset of the app inside its slot (see module docstring).
APP_OFFSET = 0x200

# Bootloader region: 16 KB default. Generous for the UART update bootloader
# (protocol + flash driver measure a few KB) without eating the app space.
_BOOTLOADER_BYTES = 16 * 1024

# Boot-state store: two pages (the power-atomic ping-pong pair in
# alloy/ota/boot_store.hpp needs exactly two independently-erasable pages).
_STORE_PAGES = 2


@dataclass(frozen=True)
class Region:
    base: int
    size: int


@dataclass(frozen=True)
class SlotLayout:
    # For uniform-page flash this is the erase page; for sector flash it is the
    # SLOT erase stride (one big sector), so the updater's page-by-page erase
    # hits each sector exactly once. Store pages are addressed explicitly.
    page_size: int
    bootloader: Region
    slot_a: Region
    slot_b: Region
    store: Region
    store_page_b: int  # base of the store's second independently-erasable page


# Every flash-controller IP the slot layout understands (uniform pages or the
# F7 sector map). Used to FIND the controller peripheral too — its name varies
# by vendor ("flash" on ST, "efc" on Microchip).
_KNOWN_FLASH_IPS = set(_FLASH_PAGE_SIZE) | {"st/flash_f7"}


def flash_controller(chip: dict[str, Any]) -> tuple[str, str] | None:
    """(peripheral_name, ip) of the chip's flash controller, if curated+known."""
    for name, periph in (chip.get("peripherals") or {}).items():
        if periph.get("uncurated"):
            continue
        ip = periph.get("ip")
        if ip in _KNOWN_FLASH_IPS:
            return name, ip
    return None


def flash_ip(chip: dict[str, Any]) -> str | None:
    """The chip's flash-controller IP, if it declares one (curated)."""
    fc = flash_controller(chip)
    return fc[1] if fc else None


def has_slot_layout(chip: dict[str, Any]) -> bool:
    """True when this chip can be partitioned (supported flash IP + enough flash).
    Quiet — used to decide whether to emit slots.hpp during gen-all."""
    try:
        slot_layout(chip)
    except EmitError:
        return False
    return True


def slot_layout(chip: dict[str, Any]) -> SlotLayout:
    """Partition the chip's flash for A/B update. Raises EmitError when the chip
    can't support it (unknown flash IP, or flash too small to be worth it)."""
    ip = flash_ip(chip)
    flash = next((m for m in chip["memories"] if m["kind"] == "flash"), None)
    if flash is None:
        raise EmitError(f"chip {chip['part']}: no flash memory in chip data")
    base = int(flash["base"], 16) if isinstance(flash["base"], str) else int(flash["base"])
    total = int(flash["size"])

    if ip == "st/flash_f7":
        return _sector_layout_f7(chip, base, total)

    page = _FLASH_PAGE_SIZE.get(ip or "")
    if page is None:
        raise EmitError(
            f"chip {chip['part']}: no A/B slot layout — flash controller IP "
            f"'{ip}' has no page-size entry (add it to emit/slots.py when the "
            f"flash HAL for it exists)")

    bl_size = _BOOTLOADER_BYTES
    store_size = _STORE_PAGES * page
    usable = total - bl_size - store_size
    slot_size = (usable // 2) // page * page  # per-slot, rounded DOWN to pages
    # An app slot smaller than 8 pages is not a useful product target.
    if slot_size < 8 * page:
        raise EmitError(
            f"chip {chip['part']}: flash too small for A/B slots "
            f"({total} B total - {bl_size} B bootloader - {store_size} B store "
            f"leaves {slot_size} B per slot)")

    slot_a = Region(base + bl_size, slot_size)
    slot_b = Region(slot_a.base + slot_size, slot_size)
    store = Region(base + total - store_size, store_size)
    return SlotLayout(page, Region(base, bl_size), slot_a, slot_b, store,
                      store.base + page)


def _sector_layout_f7(chip: dict[str, Any], base: int, total: int) -> SlotLayout:
    """F7 flash is SECTOR-based with mixed sizes (RM0431/RM0385, single bank):
    4 small sectors, one medium (4x small), then big sectors (8x small); small is
    16K on 512K parts and 32K on 1M/2M. The layout uses the natural boundaries —

        s0: bootloader | s1+s2: boot-state store | s3+s4: reserved (nvm/fs later)
        first big sector: slot A | second big sector: slot B | rest: reserved

    so the updater's erase stride (page_size = one big sector) hits each sector
    exactly once and the store's two pages are independently-erasable sectors."""
    small = 32 * 1024 if total >= 1024 * 1024 else 16 * 1024
    big = small * 8
    bigs_base = base + 4 * small + 4 * small  # 4 small + 1 medium (4x small)
    if bigs_base + 2 * big > base + total:
        raise EmitError(f"chip {chip['part']}: flash too small for the F7 A/B "
                        f"sector layout (needs two {big // 1024}K sectors)")
    return SlotLayout(
        page_size=big,
        bootloader=Region(base, small),
        slot_a=Region(bigs_base, big),
        slot_b=Region(bigs_base + big, big),
        store=Region(base + small, 2 * small),
        store_page_b=base + 2 * small,
    )


def emit_slots_header(chip: dict[str, Any]) -> str:
    """gen/alloy/slots.hpp — the one place slot addresses exist as C++. Both the
    bootloader and the app include it; the OTA core never does (it stays
    board-free and takes these as values)."""
    lay = slot_layout(chip)
    fc_name = flash_controller(chip)[0]  # slot_layout above guarantees it exists
    return f"""{_BANNER}// A/B firmware-slot layout for {chip['vendor']}/{chip['part']} — derived from the
// chip's flash geometry. Regions are erase-page-aligned (page = {lay.page_size} B).
#pragma once

#include <cstdint>

#include "alloy/device.hpp"

namespace alloy::slots {{

// The chip's flash-controller instance, whatever its vendor calls it ("flash"
// on ST, "efc" on Microchip) — bootloader/apps write flash through this.
using flash_ctrl_t = alloy::dev::{fc_name}_t;

inline constexpr std::uint32_t page_size = {lay.page_size}u;

// The app's vector table lives at slot base + app_offset; bytes [32, app_offset)
// of a slot are image-payload padding (see alloy/ota/image.hpp).
inline constexpr std::uint32_t app_offset = {APP_OFFSET:#x}u;

inline constexpr std::uintptr_t bootloader_base = {lay.bootloader.base:#010x}u;
inline constexpr std::uint32_t bootloader_size = {lay.bootloader.size}u;

inline constexpr std::uintptr_t slot_a_base = {lay.slot_a.base:#010x}u;
inline constexpr std::uint32_t slot_a_size = {lay.slot_a.size}u;
inline constexpr std::uintptr_t slot_b_base = {lay.slot_b.base:#010x}u;
inline constexpr std::uint32_t slot_b_size = {lay.slot_b.size}u;

inline constexpr std::uintptr_t store_base = {lay.store.base:#010x}u;
inline constexpr std::uint32_t store_size = {lay.store.size}u;
// The store's second independently-erasable page (== store_base + page_size on
// uniform-page flash; its own sector on sector-based flash like F7).
inline constexpr std::uintptr_t store_page_b = {lay.store_page_b:#010x}u;

}}  // namespace alloy::slots
"""
