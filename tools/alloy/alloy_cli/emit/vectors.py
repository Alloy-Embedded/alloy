"""Emit the Cortex-M vector table (C file — address constants in static
initializers are cleaner in C than C++).

Facts (entry order, IRQ names/numbers) come from chip data; the reset
handler behavior lives hand-written in src/alloy/arch/cortex_m/startup.cpp.
"""

from __future__ import annotations

from typing import Any

from .common import EmitError, register_by_name

_C_BANNER = "/* GENERATED by alloy — DO NOT EDIT (fix the data or the emitter and regenerate) */\n"

# ARMv6-M/v7-M system exception slots 1..15 (slot 0 is the initial SP).
_SYSTEM_SLOTS = [
    "Reset_Handler", "NMI_Handler", "HardFault_Handler",
    None, None, None, None, None, None, None,
    "SVC_Handler", None, None, "PendSV_Handler", "SysTick_Handler",
]


#: RL78 fixes its table at 0x00000 and gives every entry two bytes. 64 of them,
#: including the reset vector at slot 0 — there is no initial stack pointer
#: there, because the SP is loaded by software in startup.
_RL78_VECTOR_SLOTS = 64


def emit_rl78_vector_table(chip: dict[str, Any]) -> str:
    """The RL78 vector table.

    Three things differ from the Cortex-M one beside it, and each is the
    architecture rather than a preference:

      * slot 0 is the RESET VECTOR, not the initial stack pointer. RL78 loads
        SP in software, so startup does it before touching anything.
      * entries are 2 bytes, not 4 — the table is 128 bytes total and cannot
        move, because there is no VTOR.
      * several sources legitimately share one vector on this family
        (INTCSI20/INTIIC20/INTST2 are the same entry). The Cortex-M emitter
        raises on a duplicate number; here that would reject the real silicon,
        so a shared vector dispatches to every source that names it.
    """
    irqs = sorted(chip["interrupts"], key=lambda i: i["number"])
    by_number: dict[int, list[str]] = {}
    for irq in irqs:
        number = int(irq["number"])
        if not 0 <= number < _RL78_VECTOR_SLOTS:
            raise EmitError(
                f"{chip['part']}: interrupt {irq['name']} is vector {number}; "
                f"RL78 has {_RL78_VECTOR_SLOTS} (0..{_RL78_VECTOR_SLOTS - 1})")
        by_number.setdefault(number, []).append(irq["name"])

    wrappers: list[str] = []
    entries: list[str] = []
    for slot in range(_RL78_VECTOR_SLOTS):
        names = by_number.get(slot)
        if slot == 0:
            entries.append("    _start, /* reset — SP is set in software */")
            continue
        if not names:
            entries.append(f"    Default_Handler, /* {slot} unused */")
            continue
        # One wrapper per VECTOR, forwarding the vector number. Which of the
        # sharing sources actually fired is a question only the peripheral's
        # own flags can answer, so the dispatcher hands it to every handler
        # attached to the line and they check.
        handler = f"vect{slot}_Handler"
        shared = " / ".join(names)
        wrappers.append(
            f"__attribute__((weak, interrupt)) void {handler}(void) "
            f"{{ alloy_irq_dispatch({slot}u); }}  /* {shared} */")
        entries.append(f"    {handler}, /* {slot}: {shared} */")

    wrapper_block = "\n".join(wrappers)
    table = "\n".join(entries)
    shared_count = sum(1 for v in by_number.values() if len(v) > 1)
    return f"""{_C_BANNER}/* Chip: {chip['vendor']}/{chip['part']} — {len(irqs)} sources in \
{len(by_number)} vectors ({shared_count} shared) */
#include <stdint.h>

void _start(void);
void alloy_irq_dispatch(unsigned line);

/* Anything with no handler attached: stop rather than return into a source
   that is still asserting, which would spin forever without saying why. */
__attribute__((weak, interrupt)) void Default_Handler(void) {{ for (;;) {{ }} }}

{wrapper_block}

typedef void (*vector_t)(void);

/* Fixed at 0x00000 by the architecture — the linker places .vectors there and
   nothing can move it. */
__attribute__((used, section(".vectors")))
const vector_t g_alloy_vectors[{_RL78_VECTOR_SLOTS}] = {{
{table}
}};
"""


def emit_vector_table(chip: dict[str, Any]) -> str:
    irqs = sorted(chip["interrupts"], key=lambda i: i["number"])
    max_irq = irqs[-1]["number"]
    by_number = {i["number"]: i["name"] for i in irqs}
    if len(by_number) != len(irqs):
        raise EmitError("duplicate IRQ numbers in chip data")

    weak_decls: list[str] = [
        f"void {name}(void) __attribute__((weak, alias(\"Default_Handler\")));"
        for name in _SYSTEM_SLOTS
        if name is not None and name != "Reset_Handler"
    ]
    entries: list[str] = ["    (vector_t)&_estack,"]
    for slot in _SYSTEM_SLOTS:
        entries.append(f"    {slot}," if slot else "    0,")

    # Per-IRQ wrappers: WEAK functions (not aliases) whose body forwards the
    # line number to the hand-written slot dispatcher. A strong
    # <NAME>_IRQHandler anywhere in the link still overrides its wrapper —
    # the zero-latency expert path stays available.
    wrappers: list[str] = []
    for number in range(max_irq + 1):
        name = by_number.get(number)
        if name is None:
            entries.append(f"    0, /* IRQ{number} reserved */")
            continue
        handler = f"{name}_IRQHandler"
        wrappers.append(
            f"__attribute__((weak)) void {handler}(void) {{ alloy_irq_dispatch({number}u); }}"
        )
        entries.append(f"    {handler}, /* IRQ{number} */")

    decls = "\n".join(weak_decls)
    wrapper_block = "\n".join(wrappers)
    table = "\n".join(entries)
    slot_count = max_irq + 1
    return f"""{_C_BANNER}/* Chip: {chip['vendor']}/{chip['part']} — {len(irqs)} IRQ lines */

typedef void (*vector_t)(void);

extern unsigned int _estack;

void Reset_Handler(void);

void Default_Handler(void) {{
    for (;;) {{
    }}
}}

/* Per-line interrupt-handler chain heads, consumed by alloy::irq
 * (src/alloy/irq.hpp) and walked by alloy_irq_dispatch
 * (src/alloy/arch/cortex_m/irq_dispatch.cpp). One head pointer per line (opaque
 * to codegen — alloy::irq owns the chain nodes), zero-initialized. */
void *g_alloy_irq_heads[{slot_count}];
const unsigned short g_alloy_irq_slot_count = {slot_count};

void alloy_irq_dispatch(unsigned n);

{decls}

{wrapper_block}

__attribute__((used, section(".isr_vector")))
const vector_t g_vector_table[] = {{
{table}
}};
"""

def emit_xtensa_irq_data(chip: dict[str, Any], registers: dict[str, dict[str, Any]]) -> str:
    """Slot table + interrupt-matrix facts for the Xtensa irq layer.

    No vector table here — vectors.S owns the XEA2 table; VECBASE points at
    it. This TU carries only the DATA the hand-written arch code needs:
    the slot array (sized by the source count) and the resolved address of
    the DPORT PRO_INTR_MAP array.
    """
    irqs = sorted(chip["interrupts"], key=lambda i: i["number"])
    slot_count = irqs[-1]["number"] + 1

    intmap = None
    for name, periph in chip["peripherals"].items():
        if periph.get("uncurated"):
            continue  # stub carries facts but no `ip`/register model to search
        ip_doc = registers[periph["ip"]]
        for reg in ip_doc["registers"]:
            if reg["name"] == "PRO_INTR_MAP":
                addr = int(periph["base"], 16) + int(reg["offset"], 16)
                stride = reg["array"]["stride"]
                count = reg["array"]["count"]
                intmap = (addr, stride, count)
    if intmap is None:
        raise EmitError("xtensa chip has interrupts but no peripheral models PRO_INTR_MAP")
    if intmap[2] < slot_count:
        raise EmitError("interrupt sources exceed the PRO_INTR_MAP array count")

    return f"""{_C_BANNER}/* Chip: {chip['vendor']}/{chip['part']} — {len(irqs)} interrupt-matrix sources */

/* Per-line interrupt-handler chain heads, consumed by alloy::irq and walked by
 * alloy_irq_dispatch (src/alloy/arch/xtensa/irq_ctrl.cpp) via the cpu-int ->
 * source map. One head pointer per source (opaque here), zero-initialized. */
void *g_alloy_irq_heads[{slot_count}];
const unsigned short g_alloy_irq_slot_count = {slot_count};

/* DPORT PRO_INTR_MAP array (one register per source), resolved from data. */
const unsigned long g_alloy_intmap_addr = 0x{intmap[0]:08X}UL;
const unsigned short g_alloy_intmap_stride = {intmap[1]};
"""
